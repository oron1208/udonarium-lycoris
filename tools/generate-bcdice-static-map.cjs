#!/usr/bin/env node
// bcdice の全ゲームシステム/i18nを「静的指定子の遅延importマップ」に変換して出力する。
// 理由: webpackは `import(\`bcdice/.../${id}\`)` をコンテキストモジュールとして解決したが、
// esbuildはテンプレートリテラル動的importを実行時まで残すため、ブラウザで
// "Failed to resolve module specifier" になりチャット送信等が死ぬ。
// 使い方: node tools/generate-bcdice-static-map.cjs  (bcdice更新後に再実行)
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const gsDir = path.join(root, 'node_modules/bcdice/lib/bcdice/game_system');
const i18nDir = path.join(root, 'node_modules/bcdice/lib/bcdice/i18n');
const out = path.join(root, 'src/app/class/bcdice/bcdice-static-map.ts');

const q = JSON.stringify;
const gameSystems = fs.readdirSync(gsDir)
  .filter(f => f.endsWith('.js') && f !== 'index.js')
  .map(f => f.slice(0, -3))
  .sort();
const i18n = fs.readdirSync(i18nDir)
  .filter(f => f.endsWith('.json') && f !== 'i18n.json')
  .map(f => f.slice(0, -5))
  .sort();

let src = `// AUTO-GENERATED by tools/generate-bcdice-static-map.cjs — 手書き編集禁止。bcdice更新時に再生成すること。
// 静的指定子の遅延importのみ書くこと（テンプレートリテラルはesbuildで解決不能）。
type LazyModule = () => Promise<any>;

export const bcdiceGameSystems: Record<string, LazyModule> = {
`;
for (const id of gameSystems) src += `  ${q(id)}: () => import(${q('bcdice/lib/bcdice/game_system/' + id)}),\n`;
src += `};

export const bcdiceI18n: Record<string, LazyModule> = {
`;
for (const id of i18n) src += `  ${q(id)}: () => import(${q('bcdice/lib/bcdice/i18n/' + id + '.json')}),\n`;
src += `};
`;
fs.writeFileSync(out, src);
console.log(`generated ${out}: ${gameSystems.length} game systems, ${i18n.length} i18n entries`);
